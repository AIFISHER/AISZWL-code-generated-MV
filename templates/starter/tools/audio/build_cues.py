# assets/audio/lines.json (from krc_lines.py) -> src/cues.js. Real seconds, no warp.
# usage: python3 tools/audio/build_cues.py --dur 211.86 [--off 0.0] [--skip-before 30] [--bpm 125 --beat0 0.0] [--src "Kugou KRC <id>"]
# --skip-before drops header lines (title/credits) that KRC places before the first sung line. Last syllable capped at 2.6 s.
import json, argparse
p = argparse.ArgumentParser(); p.add_argument('--dur', type=float, required=True); p.add_argument('--off', type=float, default=0.0)
p.add_argument('--skip-before', type=float, default=0.0); p.add_argument('--bpm', type=float, default=120); p.add_argument('--beat0', type=float, default=0.0)
p.add_argument('--src', default='Kugou KRC'); p.add_argument('--audio', default='assets/audio/song.m4a'); a = p.parse_args()
L = [l for l in json.load(open('assets/audio/lines.json', encoding='utf-8')) if l['t'] >= a.skip_before]
lines = []
for i, l in enumerate(L):
    syl = [[round(s[0] + a.off, 3), round(s[1], 3), s[2]] for s in l['syl'] if s[2] != '']
    while syl and not syl[-1][2].strip(): syl.pop()
    if not syl: continue
    syl[-1][1] = min(syl[-1][1], 2.6)
    lines.append({'id': f'L{len(lines)+1:02d}', 't': round(syl[0][0], 3), 'end': round(syl[-1][0] + syl[-1][1], 3), 'text': ''.join(s[2] for s in syl).strip(), 'syl': syl})
out = f'// Generated by tools/audio/build_cues.py from {a.src} (word-level), offset {a.off} s.\n// Real seconds of {a.audio} ({a.dur} s).\n'
out += f'export const DURATION = {a.dur};\nexport const OFFSET = {a.off};\nexport const BEAT = {round(60/a.bpm,4)}; export const BEAT0 = {a.beat0};\n'
out += 'export const LINES = ' + json.dumps(lines, ensure_ascii=False) + ';\n'
out += 'export const CUE_LIST = [["intro", 0, "前奏"], ...LINES.map((l) => [l.id, l.t, l.text]), ["END", DURATION, "结束"]];\n'
out += 'export const CUES = Object.fromEntries(LINES.map((l) => [l.id, l.t]));\nexport const cue = (id) => CUES[id];\nexport const LINE = Object.fromEntries(LINES.map((l) => [l.id, l]));\n'
out += 'export const beat = (k) => BEAT0 + k * BEAT;\n'
open('src/cues.js', 'w', encoding='utf-8').write(out)
for l in lines: print(l['id'], l['t'], l['end'], l['text'])
